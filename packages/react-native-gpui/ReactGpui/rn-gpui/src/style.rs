//! RN view props -> GPUI `StyleRefinement` (design doc §18.13).
//!
//! Phase 1 only ever sets **paint** fields here; absolute position and size are
//! added in `node_view::RNNodeView::render`. No flex property is ever set, so
//! Taffy can never disagree with Yoga.

use gpui::{point, px, rgba, BoxShadow, Fill, Hsla, Overflow, StyleRefinement};
use rn_gpui_sys::ffi::ViewPropsFlat;

/// RN colors are 0xAARRGGBB; GPUI's `rgba()` takes 0xRRGGBBAA.
pub fn color(argb: u32) -> Hsla {
    let alpha = argb >> 24;
    rgba((argb << 8) | alpha).into()
}

pub fn to_refinement(v: &ViewPropsFlat) -> StyleRefinement {
    let mut s = StyleRefinement::default();
    if v.background_color != 0 {
        s.background = Some(Fill::from(color(v.background_color)));
    }
    // `border_widths` is `EdgesRefinement<AbsoluteLength>`: every edge is
    // `Option<AbsoluteLength>`, generated by the `Refineable` derive.
    s.border_widths.left = Some(px(v.border_widths.left).into());
    s.border_widths.top = Some(px(v.border_widths.top).into());
    s.border_widths.right = Some(px(v.border_widths.right).into());
    s.border_widths.bottom = Some(px(v.border_widths.bottom).into());
    // GPUI has one border color per element: use the top edge's for v1
    // (per-side colors -> TODO 3.8).
    if v.border_colors[1] != 0 {
        s.border_color = Some(color(v.border_colors[1]));
    }
    s.corner_radii.top_left = Some(px(v.border_radii.tl).into());
    s.corner_radii.top_right = Some(px(v.border_radii.tr).into());
    s.corner_radii.bottom_right = Some(px(v.border_radii.br).into());
    s.corner_radii.bottom_left = Some(px(v.border_radii.bl).into());
    if v.overflow_hidden {
        s.overflow.x = Some(Overflow::Hidden);
        s.overflow.y = Some(Overflow::Hidden);
    }
    if v.opacity < 1.0 {
        s.opacity = Some(v.opacity);
    }
    if !v.shadows.is_empty() {
        s.box_shadow = Some(
            v.shadows
                .iter()
                .map(|sh| BoxShadow {
                    color: color(sh.color),
                    offset: point(px(sh.dx), px(sh.dy)),
                    blur_radius: px(sh.blur),
                    spread_radius: px(sh.spread),
                    inset: sh.inset,
                })
                .collect(),
        );
    }
    s
}
