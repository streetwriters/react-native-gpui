#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const [specPath, outputPath] = process.argv.slice(2);
if (!specPath || !outputPath) {
  throw new Error('usage: generate-rust-turbomodules <NativeModule.d.ts> <output.hpp>');
}

const source = fs.readFileSync(specPath, 'utf8');
const moduleName = source.match(/MODULE_NAME\s*=\s*['"]([^'"]+)['"]/u)?.[1];
const rustType = source.match(/rn-gpui:rust-type\s+([A-Za-z_][A-Za-z0-9_]*)/u)?.[1];
if (!moduleName || !rustType) {
  throw new Error(`${specPath} must declare MODULE_NAME and // rn-gpui:rust-type TypeName`);
}

const methods = [...source.matchAll(/^\s{2}([A-Za-z_][A-Za-z0-9_]*)\(\s*[A-Za-z_][A-Za-z0-9_]*\s*:\s*string\s*\)\s*:\s*string\s*;/gmu)]
  .map((match) => match[1]);
if (methods.length === 0) {
  throw new Error(`${specPath} has no supported sync (string) => string methods`);
}

const prefix = rustType.toLowerCase();
const declarations = [
  `extern "C" const char* rn_gpui_${prefix}_module_name();`,
  ...methods.flatMap((method) => [
    `extern "C" const char* rn_gpui_${prefix}_${method}_name();`,
    `extern "C" char* rn_gpui_${prefix}_${method}(const char*);`,
    `extern "C" void rn_gpui_${prefix}_${method}_free(char*);`,
  ]),
];
const rows = methods.map((method) =>
  `  X(rn_gpui_${prefix}_module_name, rn_gpui_${prefix}_${method}_name, rn_gpui_${prefix}_${method}, rn_gpui_${prefix}_${method}_free)`,
);
const generated = `// Generated by @rn-gpui/codegen; do not edit.\n#pragma once\n\n${declarations.join('\n')}\n\n#define RN_GPUI_RUST_TURBO_MODULES(X) \\\n${rows.join(' \\\n')}\n`;
fs.mkdirSync(path.dirname(outputPath), {recursive: true});
fs.writeFileSync(outputPath, generated);
