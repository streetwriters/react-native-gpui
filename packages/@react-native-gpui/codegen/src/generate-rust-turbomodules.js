#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const inputs = process.argv.slice(2);
const outputPath = inputs.pop();
if (inputs.length === 0 || !outputPath) {
  throw new Error(
    "usage: generate-rust-turbomodules <NativeModule.d.ts>... <output.hpp>",
  );
}

const declarations = [];
const rows = [];
const moduleNames = new Set();
for (const specPath of inputs) {
  const source = fs.readFileSync(specPath, "utf8");
  const moduleName = source.match(/MODULE_NAME\s*=\s*['"]([^'"]+)['"]/u)?.[1];
  const rustType = source.match(
    /rn-gpui:rust-type\s+([A-Za-z_][A-Za-z0-9_]*)/u,
  )?.[1];
  if (!moduleName || !rustType) {
    throw new Error(
      `${specPath} must declare MODULE_NAME and // rn-gpui:rust-type TypeName`,
    );
  }
  if (moduleNames.has(moduleName))
    throw new Error(`duplicate TurboModule name: ${moduleName}`);
  moduleNames.add(moduleName);

  const methods = [
    ...source.matchAll(
      /^\s{2}([A-Za-z_][A-Za-z0-9_]*)\(\s*[A-Za-z_][A-Za-z0-9_]*\s*:\s*string\s*\)\s*:\s*string\s*;/gmu,
    ),
  ].map((match) => match[1]);
  if (methods.length !== 1) {
    throw new Error(
      `${specPath} must have exactly one supported sync (string) => string method`,
    );
  }

  const prefix = rustType.toLowerCase();
  declarations.push(`extern "C" const char* rn_gpui_${prefix}_module_name();`);
  for (const method of methods) {
    declarations.push(
      `extern "C" const char* rn_gpui_${prefix}_${method}_name();`,
      `extern "C" char* rn_gpui_${prefix}_${method}(const char*);`,
      `extern "C" void rn_gpui_${prefix}_${method}_free(char*);`,
    );
    rows.push(
      `  X(rn_gpui_${prefix}_module_name, rn_gpui_${prefix}_${method}_name, rn_gpui_${prefix}_${method}, rn_gpui_${prefix}_${method}_free)`,
    );
  }
}

const generated = `// Generated by @react-native-gpui/codegen; do not edit.\n#pragma once\n\n${declarations.join("\n")}\n\n#define RN_GPUI_RUST_TURBO_MODULES(X) \\\n${rows.join(" \\\n")}\n`;
fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, generated);
