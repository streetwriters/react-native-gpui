#!/usr/bin/env node
import { Buffer } from 'node:buffer';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const RUNTIME_SHA = 'aa59ce554aab55879b728dbb86714e13e5cb327f';
const RAW = `https://raw.githubusercontent.com/embedpdf/runtime/${RUNTIME_SHA}`;
const GIT = 'https://chromium.googlesource.com';
const LICENSE_FILES = [
  'LICENSE',
  'LICENSE.md',
  'LICENSE.txt',
  'COPYING',
  'COPYING.txt',
  'LICENSE.TXT',
];

const COMPONENTS = [
  { name: 'PDFium and EmbedPDF Runtime', files: ['LICENSE', 'NOTICE'] },
  { name: 'AGG', dir: 'third_party/agg23' },
  { name: 'Abseil', dir: 'third_party/abseil-cpp' },
  { name: 'bigint', dir: 'third_party/bigint' },
  { name: 'dragonbox', dir: 'third_party/dragonbox' },
  { name: 'fast_float', dir: 'third_party/fast_float' },
  { name: 'FP16', dir: 'third_party/fp16' },
  { name: 'FreeType', dir: 'third_party/freetype' },
  { name: 'Highway', dir: 'third_party/highway' },
  { name: 'ICU', dir: 'third_party/icu' },
  { name: 'Little CMS', dir: 'third_party/lcms' },
  { name: 'libjpeg-turbo', dir: 'third_party/libjpeg_turbo' },
  { name: 'OpenJPEG', dir: 'third_party/libopenjpeg' },
  { name: 'libpng', dir: 'third_party/libpng' },
  { name: 'LibTIFF', dir: 'third_party/libtiff' },
  { name: 'zlib', dir: 'third_party/zlib' },
];

async function text(url) {
  const response = await fetch(url);
  if (!response.ok) return null;
  return response.text();
}

const deps = await text(`${RAW}/DEPS`);

function depsLocation(dir) {
  const entry = new RegExp(
    `'${dir.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?:/src)?':\\s*(?:\\{\\s*'url':\\s*)?Var\\('chromium_git'\\)\\s*\\+\\s*'([^']+)\\.git@'\\s*\\+\\s*Var\\('([^']+)'\\)`,
  ).exec(deps);
  if (!entry) return null;
  const revision = new RegExp(`'${entry[2]}':\\s*'([0-9a-f]{40})'`).exec(deps);
  return revision ? { repo: entry[1], revision: revision[1] } : null;
}

async function licenseOf(component) {
  if (component.files) {
    const parts = [];
    for (const file of component.files) {
      parts.push((await text(`${RAW}/${file}`)) ?? '');
    }
    return {
      source: `embedpdf/runtime@${RUNTIME_SHA.slice(0, 9)}`,
      body: parts.join('\n\n'),
    };
  }
  for (const name of [...LICENSE_FILES, 'README.pdfium']) {
    const body = await text(`${RAW}/${component.dir}/${name}`);
    if (!body) continue;
    const named = /^License File:\s*(\S+)/mu.exec(body);
    const licenseText = named
      ? await text(`${RAW}/${component.dir}/${named[1]}`)
      : null;
    return {
      source: `embedpdf/runtime/${component.dir}/${licenseText ? named[1] : name}`,
      body: licenseText ?? body,
    };
  }
  const location = depsLocation(component.dir);
  if (location) {
    for (const name of LICENSE_FILES) {
      const encoded = await text(
        `${GIT}${location.repo}/+/${location.revision}/${name}?format=TEXT`,
      );
      if (encoded) {
        return {
          source: `${location.repo.slice(1)}@${location.revision.slice(0, 9)}/${name}`,
          body: Buffer.from(encoded, 'base64').toString('utf8'),
        };
      }
    }
  }
  return null;
}

const out = [
  '# Third-party notices',
  '',
  'The PDF runtime (`libembedpdf`) bundles EmbedPDF Runtime, a fork of PDFium, and the components below. Generated by `scripts/generate-notices.mjs` from the sources named in each section.',
  '',
];
const missing = [];
for (const component of COMPONENTS) {
  const license = await licenseOf(component);
  if (!license) {
    missing.push(component.name);
    continue;
  }
  out.push(
    `## ${component.name}`,
    '',
    `Source: ${license.source}`,
    '',
    '```',
    license.body.trim(),
    '```',
    '',
  );
}
fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), out.join('\n'));
if (missing.length > 0) {
  console.error(`No licence text found for: ${missing.join(', ')}`);
  process.exitCode = 1;
}
console.log(
  `Wrote THIRD_PARTY_NOTICES.md (${COMPONENTS.length - missing.length} components).`,
);
